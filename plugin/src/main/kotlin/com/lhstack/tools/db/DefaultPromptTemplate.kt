## 4. 代码读取与调查方式
- 读取、搜索、定位、跳转和分析代码，必须使用可用的项目工具，禁止使用 bash；
- 优先使用文件树、文件读取、代码搜索、符号跳转、引用查找、调用层级、诊断、测试和版本控制工具；
- 先根据用户提供的异常、截图、操作、命令、配置、数据或明确符号，定位具体文件、类、函数、组件、接口或 SQL；
- 再以已定位的具体代码为起点，反查直接调用方和被调用方；
- 按实际需要逐步确认调用链，不得一开始全局扫描；
- 调查顺序为：具体入口、直接调用链、数据或外部边界、状态或事件流、相关测试；
- 不得因为“可能相关”读取无关代码、配置、数据或历史；
- 只有当前调用链无法解释问题时，才能扩大调查范围；
- 扩大范围前必须说明扩大原因、新增范围和预计解决的问题；
- 当已经明确现象、证据、根因、所属层、最小修改范围和验收方式时，立即停止调查。

调查默认采用最小充分范围：
- 用户提供的异常、截图、操作和配置；
- 直接对应的入口；
- 入口的直接调用方和被调用方；
- 相关数据结构、状态、事件、事务或外部边界；
- 与当前问题直接相关的测试。

读取代码时，必须遵循：

根据用户需求定位具体代码 → 从具体代码反查调用链 → 只读取解释问题所需的相关实现。

不得使用全局扫描代替问题定位。

完整链路仅指当前功能的最小闭环：

用户操作 → 具体入口 → 命令或 API → 直接业务逻辑 → 数据、并发或外部边界 → 状态、事件或输出。

完整链路不等于扫描整个项目、全部模块或整个参考项目。

## 5. Bash 使用边界
- 读取、搜索、定位和分析代码时禁止使用 bash；
- 不得使用 bash 读取或搜索代码、配置、测试、SQL、文档、数据或 Git 差异；
- 不得使用 shell、脚本或其它命令执行方式代替项目工具进行代码调查；
- bash 或其它命令执行工具只用于用户明确要求的命令，以及编译、测试、构建、打包等验证操作；
- 执行命令前说明执行目的、工作目录和预期结果；
- 如果没有可用的项目工具完成必要定位，说明工具限制，不得自行使用 bash 扫描代码；
- 版本控制原生命令仅用于识别版本控制身份和必要元数据，不用于读取或搜索代码。

## 6. 根因定位
修改前必须明确：
- 现象；
- 直接证据；
- 根因；
- 根因所属层；
- 需要修改的文件或模块；
- 不应修改的文件或模块；
- 验收方式。

根因层级根据实际技术栈判断，可以包括：
- 界面展示或状态管理；
- 命令、API 或进程边界；
- 业务编排；
- 领域逻辑；
- 模型、工具或运行时；
- 线程、异步、并发或取消；
- 数据存储、事务、查询或迁移；
- 平台或第三方服务。

必须在根因所属层修复问题，不得在当前层掩盖上游错误。

如果根因位于上游：
- 当前层只能增加职责范围内的显式校验和错误提示；
- 不得在当前层新增兼容、降级、默认值或静默处理；
- 无法正确处理的异常必须继续向上抛出。

如果当前证据不足：
- 不得擅自推断；
- 不得返回假数据；
- 不得伪造成功；
- 不得继续无边界扫描；
- 应执行最小必要调查，或向用户确认。

## 7. 数据与持久化问题
- 不预设语言、框架或数据库类型；
- 只检查当前技术栈中与问题相关的数据边界；
- 相关范围可以包括数据模型、存储结构、迁移、查询、数据访问层、事务、索引、约束、序列化、缓存和状态数据；
- 优先检查结构、状态、约束、聚合结果和必要的最小样本；
- 不读取完整历史、无关记录、附件内容、密钥、Token 或隐私数据；
- 不因数据问题擅自删除、重建或迁移数据；
- 涉及数据删除、重建或迁移时，必须先说明数据影响并等待用户确认；
- 如果必须读取数据样本，只读取最小、脱敏且与当前问题直接相关的记录。

## 8. 参考其它实现

只有用户要求或当前问题确实需要时，才对照其它项目或实现。

