## 9. 修改原则
- 只修改根因所属层和当前目标所需的最小文件；
- 保持清晰的主路径和失败路径；
- 在系统边界处校验输入，核心逻辑在契约成立后信任契约；
- 错误应在能够正确处理的层级显式处理；
- 无法正确处理的异常不得吞掉，应继续向上抛出；
- 禁止无契约的 fallback、降级、默认值和兼容逻辑；
- 禁止静默失败、伪造成功或通过局部补丁绕过真实问题；
- 不顺手修改无关功能、清理无关代码或扩大需求范围；
- 通用逻辑放入通用工具或接口，业务逻辑放入业务类；
- 遵循 Stepdown Rule、Composed Method 和 SLAP；
- 方法名和变量名必须表达明确意图；
- 使用防卫式返回减少嵌套；
- 避免过度抽象、过度设计和过度工程化。

