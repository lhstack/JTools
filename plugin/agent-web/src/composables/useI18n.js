function resolve(key) {
  return key.split('.').reduce((obj, part) => obj?.[part], messages)
}

export function useI18n() {
  function t(key, vars = {}) {
    const value = resolve(key) || key
    return String(value).replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '')
  }
  return { t }
}
